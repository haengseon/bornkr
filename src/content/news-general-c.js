// 효과 줄임말: F('happiness-1 housing+3 assets-200') → { stats, issues, money }
const STAT = ['health', 'intellect', 'happiness', 'wealth', 'relations', 'leisure'];
const F = s => {
  const fx = {};
  for (const [, k, v] of (s || '').matchAll(/([a-z]+)([+-]\d+)/g)) {
    const box = STAT.includes(k) ? 'stats' : k === 'assets' || k === 'debt' ? 'money' : 'issues';
    (fx[box] ||= {})[k] = +v;
  }
  return fx;
};
const k = (when, line, fx) => ({ when, line, fx: F(fx) });
const g = (line, fx) => ({ when: () => true, line, fx: F(fx) });   // 조건 없는 일반 링크(맨 끝)
