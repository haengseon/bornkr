// 시스템 사건 문구 확충 E: 같은 sys.* 키에 시대·연령·성향·형편별 변형을 더한다(a~d 문구의 상위 집합).
// 값은 (L, ctx) => 문자열. 후보 = 기존 a~d 문구 전부 + 조건이 맞는 변형. needYear로 시대착오 제외, ctx.pick으로 결정적 선택.
// 조건(spec)은 '&'로 묶는다: e60(~1979) e80 e90 e00 e10 e20(2020~) c19(2020~2022 팬데믹기) · child teen youth mid old
// · O+/O-/C+/C-/E+/E-/A+/A-/S+/S-(성향 ≥65/≤35) · rural urban(태어난 곳) · poor rich(출생 소득 분위 ≤2/≥4) · wed solo(혼인 상태). 빈 문자열 = 항상.
import a from './system-text-a.js';
import b from './system-text-b.js';
import c from './system-text-c.js';
import d from './system-text-d.js';
import { needYear } from '../engine/anachro.js';
import { DEFAULT_TEXT } from '../engine/text.js';   // 순환 import: 호출 시점에만 읽는다

const OLD = { ...a, ...b, ...c, ...d };
const TR = { O: 'open', C: 'consc', E: 'extra', A: 'agree', S: 'sens' };
const PRED = {
  e60: L => L.year <= 1979, e80: L => L.year >= 1980 && L.year <= 1989, e90: L => L.year >= 1990 && L.year <= 1999,
  e00: L => L.year >= 2000 && L.year <= 2009, e10: L => L.year >= 2010 && L.year <= 2019, e20: L => L.year >= 2020,
  c19: L => L.year >= 2020 && L.year <= 2022,
  child: L => L.age < 13, teen: L => L.age >= 13 && L.age <= 18, youth: L => L.age >= 19 && L.age <= 39,
  mid: L => L.age >= 40 && L.age <= 64, old: L => L.age >= 65,
  rural: L => L.birth?.urban === false, urban: L => L.birth?.urban === true,
  poor: L => (L.birth?.quintile ?? 3) <= 2, rich: L => (L.birth?.quintile ?? 3) >= 4,
  wed: L => !!L.family?.married, solo: L => !L.family?.married && !L.family?.partner,
};
export const ok = (L, spec) => !spec || spec.split('&').every(t => {
  if (PRED[t]) return PRED[t](L);
  const v = L.traits?.[TR[t[0]]] ?? 50;
  return t[1] === '+' ? v >= 65 : v <= 35;
});
export const ROWS = {};
const T = {};
const K = (key, ...rows) => {
  ROWS[key] = rows;
  T[key] = (L, ctx) => {
    L = L || { year: 2000, age: 20 };
    const o = OLD[key] ?? DEFAULT_TEXT[key];
    let pool = typeof o === 'function' ? [o(L, ctx)] : Array.isArray(o) ? [...o] : o ? [o] : [];
    for (const [spec, ...txt] of rows) if (ok(L, spec)) pool.push(...txt);
    const f = pool.filter(s => typeof s === 'string' && needYear(s) <= L.year);
    pool = f.length ? f : pool;
    return ctx?.pick ? ctx.pick(pool) : pool[0];
  };
};

