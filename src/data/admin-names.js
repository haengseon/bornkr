const PARSED = {};
const parse = id => (PARSED[id] ??= HIST[id]?.split('|').map(s => {
  const [, from, rest] = /^(\d+) ?(.*)$/.exec(s), [nm, dongs] = rest.split(':'), m = /^([a-z]+)>(.*)$/.exec(nm);
  return { from: +from, sido: m?.[1], name: (m ? m[2] : nm).trim(), dongs: dongs?.split(',') };
}));

// 그해 시도 명칭. 광역시 승격 전이면 '경북 대구시'처럼 모 도 + 시.
export function sidoAt(key, year = 9999, short = false) {
  const e = SIDO[key]?.findLast(x => x[0] <= year);
  if (e) return short ? e[2] : e[1];
  const p = METRO_PARENT[key];
  return p ? `${sidoAt(p[0], year, short)} ${p[1]}` : (SIDO[key]?.[0][short ? 2 : 1] ?? '');
}

// 그해 시군구 명칭: { sido(그 시기 소속 시도 키, 없으면 null), name(시·구·군 + 군이면 읍) }. dong은 일반구·읍 판정에만 쓰고 표기하지 않는다.
export function nameAt(id, year = 9999, dong = null) {
  const d = dong ? String(dong).replace(/\(.*\)$/, '') : null;
  let e = null;
  for (const x of parse(id) ?? []) if (x.from <= year && (!x.dongs || x.dongs.includes(dong))) e = x;
  let name = e ? e.name : NOW[id] ?? '';
  if (/군$/.test(name) && d?.endsWith('읍') && (EUP[d] ?? 0) <= year) {
    const rn = EUP_RENAME[d];
    name += ' ' + (rn && year >= rn[0] ? rn[1] : d);
  }
  return { sido: e?.sido ?? null, name };
}
