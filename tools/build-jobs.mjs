  75351: '건물 냉동·공조기 정비원', 81124: '사탕·초콜릿 제조 기계 조작원', 81140: '과일·채소 가공 기계 조작원',
  83112: '석유·가스 정제 장치 조작원', 83119: '석유·가스 제조 제어 장치 조작원', 83121: '화학물 분쇄·혼합기 조작원',
