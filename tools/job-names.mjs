export function everydayJobName(code, official, previous = official) {
  if (NAMES[code]) return NAMES[code];
  let name = previous.replace(/^그 외 /, '').replaceAll('‧', '·');
  // 설비·업무의 종류는 남기고 통계 분류 특유의 어미만 정리한다.
  name = name.replace(/ 기술자 및 연구원$/, ' 기술자')
    .replace(/ 관련 관리자$/, ' 관리자')
    .replace(/ 관련 단순 종사원$/, ' 보조인력')
    .replace(/ 관련 기능 종사원$/, ' 기능공')
    .replace(/ 관련 종사원$/, ' 종사자')
    .replace(/ 종사원$/, ' 직원')
    .replace(/ 사무원$/, ' 사무직')
    .replace(/ 판매원$/, ' 매장 직원')
    .replace(/ 영업원$/, ' 영업사원')
    .replace(/ 운전원$/, ' 기사')
    .replace(/ 설치 및 정비원$/, ' 설치·정비 기사')
    .replace(/ 설치 및 수리원$/, ' 설치·수리 기사')
    .replace(/ 정비원$/, ' 정비사');
  // 생산설비를 다루는 일은 일상적인 '생산설비 담당자'로 표현한다.
  if (/ 조작원$/.test(name)) {
    name = name.replace(/ 관련 /g, ' ').replace(/ 제조 기계 조작원$/, ' 생산설비 담당자')
      .replace(/ 제조 관련 기계 조작원$/, ' 생산설비 담당자')
      .replace(/ 생산기 조작원$/, ' 생산설비 담당자')
      .replace(/ 제조기 조작원$/, ' 생산설비 담당자')
      .replace(/ 기계 조작원$/, ' 설비 담당자')
      .replace(/ 장치 조작원$/, ' 설비 담당자')
      .replace(/ 조작원$/, ' 운전 담당자');
  }
  return name.replace(/ 및 /g, '·');
}
